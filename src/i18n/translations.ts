/**
 * Intelligent translator between French and English with punctuation preservation,
 * case sensitivity awareness, and pattern matching.
 */
export function translateText(text: string, lang: Language): string {
  if (!text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // Don't translate pure numbers or currency tokens alone
  if (/^[\d\s.,+%€$£-]+$/.test(trimmed)) return text;

  if (lang === 'en') {
    // 1. Direct exact phrase match
    if (frToEnPhrases[trimmed]) {
      return text.replace(trimmed, frToEnPhrases[trimmed]);
    }

    const lower = trimmed.toLowerCase();

    // 2. Case-insensitive phrase match
    if (lowerFrToEnPhrases[lower]) {
      return text.replace(trimmed, lowerFrToEnPhrases[lower]);
    }

    // 3. Exact lowercase match from dictionary
    if (translations.en[lower]) {
      const val = translations.en[lower];
      const matchCase = (trimmed[0] === trimmed[0].toUpperCase()) ? (val.charAt(0).toUpperCase() + val.slice(1)) : val;
      return text.replace(trimmed, matchCase);
    }

    // 4. Dynamic regex patterns
    for (const p of dynamicFrToEnPatterns) {
      const match = trimmed.match(p.pattern);
      if (match) {
        return text.replace(trimmed, p.replace(match));
      }
    }

    // 5. Clean trailing/leading punctuation (: ! ? . - • ( ) [ ])
    const punctuationRegex = /^([:\s\-•!?.\(\)\[\]]+)?(.*?)([:\s\-•!?.\(\)\[\]]+)?$/;
    const match = trimmed.match(punctuationRegex);
    if (match) {
      const prefix = match[1] || '';
      const core = match[2] || '';
      const suffix = match[3] || '';
      if (core) {
        if (frToEnPhrases[core]) {
          return prefix + frToEnPhrases[core] + suffix;
        }
        const coreLower = core.toLowerCase();
        if (lowerFrToEnPhrases[coreLower]) {
          return prefix + lowerFrToEnPhrases[coreLower] + suffix;
        }
        if (translations.en[coreLower]) {
          const val = translations.en[coreLower];
          const matchCase = (core[0] === core[0].toUpperCase()) ? (val.charAt(0).toUpperCase() + val.slice(1)) : val;
          return prefix + matchCase + suffix;
        }
      }
    }
  } else {
    // English -> French (for reverting or French mode)
    if (enToFrPhrases[trimmed]) {
      return text.replace(trimmed, enToFrPhrases[trimmed]);
    }

    const lower = trimmed.toLowerCase();

    // 2. Case-insensitive phrase match
    if (lowerEnToFrPhrases[lower]) {
      return text.replace(trimmed, lowerEnToFrPhrases[lower]);
    }

    if (translations.fr[lower]) {
      const val = translations.fr[lower];
      const matchCase = (trimmed[0] === trimmed[0].toUpperCase()) ? (val.charAt(0).toUpperCase() + val.slice(1)) : val;
      return text.replace(trimmed, matchCase);
    }

    for (const p of dynamicEnToFrPatterns) {
      const match = trimmed.match(p.pattern);
      if (match) {
        return text.replace(trimmed, p.replace(match));
      }
    }

    const punctuationRegex = /^([:\s\-•!?.\(\)\[\]]+)?(.*?)([:\s\-•!?.\(\)\[\]]+)?$/;
    const match = trimmed.match(punctuationRegex);
    if (match) {
      const prefix = match[1] || '';
      const core = match[2] || '';
      const suffix = match[3] || '';
      if (core) {
        if (enToFrPhrases[core]) {
          return prefix + enToFrPhrases[core] + suffix;
        }
        const coreLower = core.toLowerCase();
        if (lowerEnToFrPhrases[coreLower]) {
          return prefix + lowerEnToFrPhrases[coreLower] + suffix;
        }
        if (translations.fr[coreLower]) {
          const val = translations.fr[coreLower];
          const matchCase = (core[0] === core[0].toUpperCase()) ? (val.charAt(0).toUpperCase() + val.slice(1)) : val;
          return prefix + matchCase + suffix;
        }
      }
    }
  }

  return text;
}
